"""
Table Specification Schema

Defines the table specification structure for cross-tabulation analysis.
This matches the table_specification.jsonc format generated by Stage 2 AI.

Structure:
- metadata: Document metadata
- filter_clause: Data filtering rules
- row_indicators: Row indicator specifications
- column_indicators: Column indicator specifications
"""

from dataclasses import dataclass, field
from typing import Optional, List, Dict, Any, Union
from enum import Enum
from datetime import datetime


# ============================================================================
# Enums
# ============================================================================

class VariableSuffix(str, Enum):
    """Suffix types indicating variable transformation."""
    RAW = "_raw"          # Raw SPSS variable, no transformation
    BIN = "_bin"          # Binary (0/1, Yes/No)
    CAT = "_cat"          # Categorical recoded
    T2B = "_t2b"          # Top 2 Box (highest categories)
    B2B = "_b2b"          # Bottom 2 Box (lowest categories)
    NPS = "_nps"          # NPS categorization
    SCA = "_sca"          # Scalar/continuous
    IDX = "_idx"          # Computed index
    Z = "_z"              # Z-score normalized
    PCT = "_pct"          # Percentile rank


class QuestionType(str, Enum):
    """Types of questions in the questionnaire."""
    SINGLE_CHOICE = "Single Choice"
    MULTIPLE_CHOICE = "Multiple Choice"
    MATRIX = "Matrix"
    RATING_SCALE = "Rating Scale"
    NUMERIC_INPUT = "Numeric Input"
    OPEN_ENDED = "Open Ended"


class TabulationType(str, Enum):
    """Types of tabulation statistics."""
    CATEGORICAL = "categorical"
    SCALAR = "scalar"


class MetricType(str, Enum):
    """Types of metrics for tabulation."""
    COLUMN_PERCENT = "column_percent"
    DESCRIPTIVE_STATISTICS = "descriptive_statistics"



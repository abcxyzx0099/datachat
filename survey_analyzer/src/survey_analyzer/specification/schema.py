@dataclass
class TableSpecification:
    """
    Root table specification document.

    This is the primary artifact generated by Stage 2 (analyzer-tablespec-gen)
    and consumed by Stage 3 (analyzer-crosstabs) for cross-tabulation generation.

    Structure:
        - metadata: Document metadata (spec_id, project_id, dataset_id, description)
        - filter_clause: Data filtering rules (age_min, age_max, exclude_incomplete)
        - weight_indicator: Weight variable name
        - row_indicators: List of row indicator specifications
        - column_indicators: List of column indicator specifications
    """
    # Document metadata
    metadata: Dict[str, str]
    filter_clause: Dict[str, Any] = field(default_factory=dict)
    weight_indicator: Optional[str] = None

    # Indicators (lists of IndicatorSpec)
    row_indicators: List[IndicatorSpec] = field(default_factory=list)
    column_indicators: List[IndicatorSpec] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        """Convert to dictionary for JSON serialization."""
        return {
            "metadata": self.metadata,
            "filter_clause": self.filter_clause,
            "weight_indicator": self.weight_indicator,
            "row_indicators": [ind.to_dict() for ind in self.row_indicators],
            "column_indicators": [ind.to_dict() for ind in self.column_indicators]
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "TableSpecification":
        """Create instance from dictionary (for loading from JSON)."""
        # Handle row_indicators - support both new (array) and old (dict) formats
        row_indicators_data = data.get("row_indicators", [])
        if isinstance(row_indicators_data, list):
            # New format: array of indicators
            row_indicators = [
                IndicatorSpec.from_dict(ind)
                for ind in row_indicators_data
            ]
        else:
            # Old format: dict with indicator code as key
            row_indicators = [
                IndicatorSpec.from_dict(details, code)
                for code, details in row_indicators_data.items()
            ]

        # Handle column_indicators - support both new (array) and old (dict) formats
        column_indicators_data = data.get("column_indicators", [])
        if isinstance(column_indicators_data, list):
            # New format: array of indicators
            column_indicators = [
                IndicatorSpec.from_dict(ind)
                for ind in column_indicators_data
            ]
        else:
            # Old format: dict with indicator code as key
            column_indicators = [
                IndicatorSpec.from_dict(details, code)
                for code, details in column_indicators_data.items()
            ]

        return cls(
            metadata=data.get("metadata", {}),
            filter_clause=data.get("filter_clause", {}),
            weight_indicator=data.get("weight_indicator"),
            row_indicators=row_indicators,
            column_indicators=column_indicators
        )

    def get_indicator_by_code(self, code: str) -> Optional[IndicatorSpec]:
        """Find an indicator by its code."""
        for ind in self.row_indicators:
            if ind.indicator_code == code:
                return ind
        for ind in self.column_indicators:
            if ind.indicator_code == code:
                return ind
        return None

    def validate(self) -> List[str]:
        """
        Validate the table specification structure.

        Returns:
            List of error messages (empty if valid).
        """
        errors = []

        # Check metadata
        required_metadata = ["spec_id", "project_id"]
        for field in required_metadata:
            if field not in self.metadata:
                errors.append(f"Missing required metadata field: '{field}'")

        # Check indicators exist
        if not self.row_indicators:
            errors.append("No row_indicators defined")

        if not self.column_indicators:
            errors.append("No column_indicators defined")

        # Validate each indicator (row)
        for i, indicator in enumerate(self.row_indicators):
            code = indicator.indicator_code or f"index_{i}"
            if not indicator.indicator_label:
                errors.append(f"row_indicators[{i}] ({code}): missing indicator_label")
            if not indicator.base_variables:
                errors.append(f"row_indicators[{i}] ({code}): no base_variables defined")
            if not indicator.tabulation_type:
                errors.append(f"row_indicators[{i}] ({code}): missing tabulation_type")
            if not indicator.tabulation_metric:
                errors.append(f"row_indicators[{i}] ({code}): missing tabulation_metric")

        # Validate each indicator (column)
        for i, indicator in enumerate(self.column_indicators):
            code = indicator.indicator_code or f"index_{i}"
            if not indicator.indicator_label:
                errors.append(f"column_indicators[{i}] ({code}): missing indicator_label")
            if not indicator.base_variables:
                errors.append(f"column_indicators[{i}] ({code}): no base_variables defined")
            if not indicator.tabulation_type:
                errors.append(f"column_indicators[{i}] ({code}): missing tabulation_type")
            if not indicator.tabulation_metric:
                errors.append(f"column_indicators[{i}] ({code}): missing tabulation_metric")

        return errors



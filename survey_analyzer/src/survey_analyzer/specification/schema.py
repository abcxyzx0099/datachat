@dataclass
class BaseVariable:
    """
    A single base variable in an indicator.

    Each base variable represents a target variable with its transformation.
    All variables in an indicator typically share the same suffix.

    The generation field uses simplified SPSS-like syntax with only parentheses,
    e.g., "(1 THRU 2=1) (ELSE=0)" - no "RECODE" keyword needed.

    Attributes:
        name: Target variable name (with suffix, e.g., "Q5_SATISFACTION_cat")
        label: Human-readable variable label
        generation: Simplified transformation syntax with parentheses only, null for raw
    """
    name: str = ""
    label: str = ""
    generation: Optional[str] = None

    def to_dict(self) -> Dict[str, Any]:
        """Convert to dictionary for JSON serialization."""
        return {
            "name": self.name,
            "label": self.label,
            "generation": self.generation
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "BaseVariable":
        """
        Create instance from dictionary (for loading from JSON).

        Args:
            data: Dictionary containing variable fields
        """
        return cls(
            name=data.get("name", ""),
            label=data.get("label", ""),
            generation=data.get("generation")
        )

    def is_raw(self) -> bool:
        """Check if this is a raw variable (no transformation)."""
        return self.generation is None or self.generation == ""

    def get_suffix(self) -> str:
        """Extract the suffix from the variable name."""
        # Find common suffixes
        for suffix in ["_idx", "_pct", "_z", "_sca", "_nps", "_b2b", "_t2b", "_bin", "_cat", "_raw"]:
            if self.name.endswith(suffix):
                return suffix
        return "_cat"  # Default

    def is_categorical(self) -> bool:
        """Check if this is a categorical variable type."""
        suffix = self.get_suffix()
        return suffix in ["_raw", "_bin", "_cat", "_t2b", "_b2b", "_nps"]

    def is_scalar(self) -> bool:
        """Check if this is a scalar variable type."""
        suffix = self.get_suffix()
        return suffix in ["_sca", "_idx", "_z", "_pct"]



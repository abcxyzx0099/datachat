@dataclass
class QuestionRef:
    """
    Reference to a questionnaire question.

    Attributes:
        code: SPSS variable prefix (Q1, S1, D1)
        label: Short question label
        type: Question type (Single Choice, Multiple Choice, etc.)
    """
    code: str
    label: str
    type: QuestionType

    def to_dict(self) -> Dict[str, Any]:
        """Convert to dictionary for JSON serialization."""
        return {
            "code": self.code,
            "label": self.label,
            "type": self.type.value
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "QuestionRef":
        """Create instance from dictionary (for loading from JSON)."""
        return cls(
            code=data["code"],
            label=data["label"],
            type=QuestionType(data["type"])
        )



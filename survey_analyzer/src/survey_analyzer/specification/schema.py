def create_empty_spec(
    spec_id: str = "new_spec",
    project_id: str = "default_project",
    dataset_id: str = "default_dataset",
    **kwargs
) -> TableSpecification:
    """Create an empty table specification document.

    Args:
        spec_id: Specification ID
        project_id: Project ID
        dataset_id: Dataset ID
        **kwargs: Additional metadata fields (e.g., source_file for backward compatibility)

    Returns:
        Empty TableSpecification instance
    """
    metadata = {
        "spec_id": spec_id,
        "project_id": project_id,
        "dataset_id": dataset_id,
        "description": "Table specification"
    }
    # Add any extra kwargs to metadata (for backward compatibility)
    metadata.update(kwargs)

    return TableSpecification(
        metadata=metadata,
        filter_clause={},
        row_indicators=[],
        column_indicators=[]
    )


def load_from_file(filepath: str) -> TableSpecification:
    """Load table specification from JSONC file."""
    import json
    with open(filepath, 'r') as f:
        data = json.load(f)
    return TableSpecification.from_dict(data)


def save_to_file(spec: TableSpecification, filepath: str):
    """Save table specification to JSONC file."""
    import json
    with open(filepath, 'w') as f:
        json.dump(spec.to_dict(), f, indent=2)



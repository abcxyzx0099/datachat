@dataclass
class IndicatorSpec:
    """
    Defines an indicator for cross-tabulation analysis.

    An indicator can have:
    - A unique indicator code (identifier)
    - A related questionnaire question (code and type)
    - Tabulation type and metric (top-level, parallel with question fields)
    - Three parallel base variable fields: variables, transformations, value_labels

    NOTE: In the new JSON structure, row_indicators and column_indicators are ARRAYS,
    and indicator_code is a field inside each indicator object (parallel with other fields).

    NOTE: Three parallel fields for base variables (at same level, not nested):
        - "base_variables": Dictionary of {variable_name: label}
        - "base_variables_transformations": Dictionary of {variable_name: SPSS_syntax}
        - "base_variables_value_labels": Dictionary of {code: label} (shared value labels)

    Transformation format:
        - Full SPSS RECODE syntax: "RECODE source_var (rules) INTO target_var"
        - Source variable is the original (no suffix like _raw)
        - Example: "RECODE Q5_SAT (1 THRU 2=1) (3=2) (4 THRU 5=3) INTO Q5_SAT_cat"
        - For raw variables: null or omitted

    NOTE: base_variables_value_labels is a DICTIONARY of shared value labels
    (code -> label mapping) that applies to all variables in this indicator.

    Attributes:
        indicator_code: Unique identifier for the indicator
        indicator_label: Human-readable label
        question_code: SPSS variable identifier for the related question
        question_type: Question type (Single Choice, Multiple Choice, Matrix, etc.)
        tabulation_type: Type of variable (categorical or scalar)
        tabulation_metric: Metric to compute (column_percent or descriptive_statistics)
        base_variables: Dictionary of variable names to labels
        base_variables_transformations: Dictionary of variable names to SPSS syntax
        base_variables_value_labels: Dictionary of value codes to labels
    """
    indicator_code: str = ""  # Required field - unique identifier
    indicator_label: str = ""
    question_code: str = ""
    question_type: QuestionType = QuestionType.SINGLE_CHOICE
    tabulation_type: Optional[TabulationType] = None  # Auto-detected if None
    tabulation_metric: Optional[MetricType] = None  # Auto-detected if None
    base_variables: Dict[str, str] = field(default_factory=dict)  # name → label
    base_variables_transformations: Optional[Dict[str, str]] = None  # name → SPSS syntax
    base_variables_value_labels: Optional[Dict[str, str]] = None  # code → label

    def __post_init__(self):
        """Set default tabulation_type and tabulation_metric if not provided."""
        if self.tabulation_type is None or self.tabulation_metric is None:
            # Auto-detect from base_variables
            if self.base_variables:
                first_var_name = next(iter(self.base_variables.keys()))
                # Check suffix to determine type
                if any(first_var_name.endswith(suffix) for suffix in ["_sca", "_idx", "_z", "_pct"]):
                    if self.tabulation_type is None:
                        self.tabulation_type = TabulationType.SCALAR
                    if self.tabulation_metric is None:
                        self.tabulation_metric = MetricType.DESCRIPTIVE_STATISTICS
                else:
                    # Default to categorical for _raw, _bin, _cat, _t2b, _b2b, _nps
                    if self.tabulation_type is None:
                        self.tabulation_type = TabulationType.CATEGORICAL
                    if self.tabulation_metric is None:
                        self.tabulation_metric = MetricType.COLUMN_PERCENT
            else:
                # No base variables - set defaults
                if self.tabulation_type is None:
                    self.tabulation_type = TabulationType.CATEGORICAL
                if self.tabulation_metric is None:
                    self.tabulation_metric = MetricType.COLUMN_PERCENT

    def to_dict(self) -> Dict[str, Any]:
        """Convert to dictionary for JSON serialization."""
        return {
            "indicator_code": self.indicator_code,
            "indicator_label": self.indicator_label,
            "question_code": self.question_code,
            "question_type": self.question_type.value if isinstance(self.question_type, QuestionType) else self.question_type,
            "tabulation_type": self.tabulation_type.value if isinstance(self.tabulation_type, TabulationType) else self.tabulation_type,
            "tabulation_metric": self.tabulation_metric.value if isinstance(self.tabulation_metric, MetricType) else self.tabulation_metric,
            "base_variables": self.base_variables,
            "base_variables_transformations": self.base_variables_transformations,
            "base_variables_value_labels": self.base_variables_value_labels,
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any], code: str = None) -> "IndicatorSpec":
        """
        Create instance from dictionary (for loading from JSON).

        Args:
            data: Dictionary containing indicator fields
            code: Optional indicator code (when not in data)
        """
        # Support both old format (questionnaire_questions) and new format (question_code, question_type)
        if "question_code" in data:
            # New format
            question_code = data.get("question_code", "")
            question_type = QuestionType(data.get("question_type", "Single Choice"))
        elif "questionnaire_questions" in data and data["questionnaire_questions"]:
            # Old format: extract from first questionnaire question
            first_q = data["questionnaire_questions"][0]
            question_code = first_q.get("code", "")
            question_type = QuestionType(first_q.get("type", "Single Choice"))
        else:
            # Fallback
            question_code = ""
            question_type = QuestionType.SINGLE_CHOICE

        # Handle base_variables - support multiple formats for backward compatibility
        base_vars = data.get("base_variables", {})
        base_vars_transformations = data.get("base_variables_transformations")
        base_vars_value_labels = data.get("base_variables_value_labels")

        # Check if old nested format (with variable_list, generation_rules, unified_values)
        if isinstance(base_vars, dict) and "variable_list" in base_vars:
            # Old nested format - extract and convert to parallel fields
            base_vars = base_vars.get("variable_list", {})
            base_vars_transformations = base_vars.get("generation_rules")
            base_vars_value_labels = base_vars.get("unified_values")
        elif isinstance(base_vars, list):
            # Legacy list format - convert
            new_vars = {}
            new_transforms = {}
            for bv in base_vars:
                name = bv.get("name", "")
                if name:
                    new_vars[name] = bv.get("label", "")
                    gen = bv.get("generation")
                    if gen:
                        new_transforms[name] = gen
            base_vars = new_vars
            base_vars_transformations = new_transforms if new_transforms else None
            # value_labels would be in a separate field
            base_vars_value_labels = data.get("base_variables_values") or data.get("unified_values")

        # Handle tabulation configuration - support both old and new formats
        tabulation_type = None
        tabulation_metric = None

        # New format: tabulation_type and tabulation_metric at top level
        if "tabulation_type" in data:
            tabulation_type = TabulationType(data["tabulation_type"])
        if "tabulation_metric" in data:
            tabulation_metric = MetricType(data["tabulation_metric"])

        # Old format: tabulation_statistics wrapper (for backward compatibility)
        if data.get("tabulation_statistics") and (tabulation_type is None or tabulation_metric is None):
            stats_data = data["tabulation_statistics"]
            if tabulation_type is None and "type" in stats_data:
                tabulation_type = TabulationType(stats_data["type"])
            if tabulation_metric is None and "metric" in stats_data:
                tabulation_metric = MetricType(stats_data["metric"])

        # Support both old and new formats
        ind_code = data.get("indicator_code") or code

        return cls(
            indicator_code=ind_code,
            indicator_label=data.get("indicator_label", ""),
            question_code=question_code,
            question_type=question_type,
            tabulation_type=tabulation_type,
            tabulation_metric=tabulation_metric,
            base_variables=base_vars,
            base_variables_transformations=base_vars_transformations,
            base_variables_value_labels=base_vars_value_labels,
        )

    def get_scenario_type(self) -> str:
        """
        Determine the crosstab scenario type based on configuration.

        Returns:
            Scenario type: cat_single, cat_multi, scalar_single, or scalar_multi
        """
        var_count = len(self.base_variables)

        if self.tabulation_type == TabulationType.CATEGORICAL:
            if var_count == 1:
                return "cat_single"
            else:
                return "cat_multi"
        else:  # SCALAR
            if var_count == 1:
                return "scalar_single"
            else:
                return "scalar_multi"



"""
Table Specification Schema

Defines the consolidated table specification structure that combines:
- Indicator definitions
- Recoding rules
- Table specifications (column definitions, metrics, grouping rules)
- Output settings

This is a unified artifact generated by AI (via skills) and consumed by
the library modules for computation.
"""

from dataclasses import dataclass, field
from typing import Optional, List, Dict, Any, Union, Literal
from enum import Enum
from datetime import datetime


# ============================================================================
# Enums
# ============================================================================

class MetricType(str, Enum):
    """Types of metrics for cross-tabulation tables."""
    COUNT = "count"
    ROW_PERCENT = "row_percent"
    COLUMN_PERCENT = "column_percent"
    TOTAL_PERCENT = "total_percent"
    MEAN = "mean"
    MEDIAN = "median"
    STD_DEV = "std_dev"
    MIN = "min"
    MAX = "max"


class AggregationType(str, Enum):
    """Types of aggregation for indicator computation."""
    MEAN = "mean"
    SUM = "sum"
    COUNT = "count"
    MEDIAN = "median"
    MODE = "mode"
    WEIGHTED_MEAN = "weighted_mean"


class RecodingType(str, Enum):
    """Types of variable recoding."""
    VALUE_MAP = "value_map"  # Direct value-to-value mapping
    RANGE_MAP = "range_map"  # Range-based mapping
    CONDITION = "condition"  # Conditional expressions


class TableType(str, Enum):
    """Types of tables to generate."""
    CROSSTAB = "crosstab"  # Cross-tabulation (row by column)
    FREQUENCY = "frequency"  # Single variable frequency table
    SUMMARY = "summary"  # Summary statistics (mean, median, etc.)


class VariableSource(str, Enum):
    """Source of variable definition."""
    RAW = "raw"  # Original variable from .sav file
    RECODED = "recoded"  # Recoded variable
    INDICATOR = "indicator"  # Computed indicator


# ============================================================================
# Recoding Rules
# ============================================================================

@dataclass
class ValueMapping:
    """Direct value-to-value mapping."""
    original: Union[str, int, float]
    recoded: Union[str, int, float]


@dataclass
class RangeMapping:
    """Range-based mapping (inclusive ranges)."""
    min_value: Optional[Union[int, float]] = None
    max_value: Optional[Union[int, float]] = None
    recoded_value: Union[str, int, float] = ""
    inclusive: bool = True


@dataclass
class RecodingRule:
    """
    Defines how to recode a variable.

    Examples:
        Value mapping: {1: "Strongly Agree", 2: "Agree", 3: "Neutral"}
        Range mapping: age <= 30 -> "Young", 31-50 -> "Middle", 51+ -> "Senior"
    """
    variable: str  # Source variable name
    new_variable: Optional[str] = None  # Output variable name (if different)
    type: RecodingType = RecodingType.VALUE_MAP
    label: Optional[str] = None  # Variable label

    # For VALUE_MAP type
    value_mappings: Dict[Union[str, int, float], Union[str, int, float]] = field(default_factory=dict)

    # For RANGE_MAP type
    range_mappings: List[RangeMapping] = field(default_factory=list)

    # For CONDITION type
    conditions: List[str] = field(default_factory=list)  # PSPP-style conditions
    condition_values: List[Union[str, int, float]] = field(default_factory=list)

    # Value labels for recoded values
    value_labels: Dict[Union[str, int, float], str] = field(default_factory=dict)

    # Validation
    missing_values: List[Union[str, int, float]] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        """Convert to dictionary for JSON serialization."""
        return {
            "variable": self.variable,
            "new_variable": self.new_variable,
            "type": self.type.value,
            "label": self.label,
            "value_mappings": self.value_mappings,
            "range_mappings": [
                {
                    "min_value": r.min_value,
                    "max_value": r.max_value,
                    "recoded_value": r.recoded_value,
                    "inclusive": r.inclusive
                }
                for r in self.range_mappings
            ],
            "conditions": self.conditions,
            "condition_values": self.condition_values,
            "value_labels": self.value_labels,
            "missing_values": self.missing_values,
        }


# ============================================================================
# Indicators
# ============================================================================

@dataclass
class VariableRef:
    """Reference to a variable with optional recoding."""
    name: str  # Variable name
    source: VariableSource = VariableSource.RAW
    recoded_as: Optional[str] = None  # If using a recoded version
    weight: float = 1.0  # Weight for aggregation


@dataclass
class Indicator:
    """
    Defines an indicator computed from multiple variables.

    Examples:
        - Customer Satisfaction: mean of q1, q2, q3 (recoded 1-5 to 0-100)
        - Brand Awareness: count of awareness mentions across q10-q15
    """
    id: str  # Unique identifier (e.g., "ind_001")
    name: str  # Human-readable name
    description: Optional[str] = None

    # Variables that make up this indicator
    variables: List[VariableRef] = field(default_factory=list)

    # Aggregation method
    aggregation: AggregationType = AggregationType.MEAN

    # Recoding applied before aggregation
    recoding: Optional[RecodingRule] = None

    # Value labels for indicator categories
    value_labels: Dict[Union[str, int, float], str] = field(default_factory=dict)

    # Display settings
    format_string: Optional[str] = None  # e.g., "{:.1f}", "{:.0%}"
    reverse_coded: bool = False  # If true, reverse the scale

    def to_dict(self) -> Dict[str, Any]:
        """Convert to dictionary for JSON serialization."""
        return {
            "id": self.id,
            "name": self.name,
            "description": self.description,
            "variables": [
                {
                    "name": v.name,
                    "source": v.source.value,
                    "recoded_as": v.recoded_as,
                    "weight": v.weight
                }
                for v in self.variables
            ],
            "aggregation": self.aggregation.value,
            "recoding": self.recoding.to_dict() if self.recoding else None,
            "value_labels": self.value_labels,
            "format_string": self.format_string,
            "reverse_coded": self.reverse_coded,
        }


# ============================================================================
# Table Specifications
# ============================================================================

@dataclass
class TableDimension:
    """
    Defines a dimension (row or column) in a cross-tabulation table.

    Can reference:
    - Raw variable
    - Recoded variable
    - Indicator
    """
    variable: str  # Variable name or indicator ID
    source: VariableSource = VariableSource.RAW
    label_override: Optional[str] = None  # Custom label for display
    sort_order: Optional[str] = None  # "asc", "desc", or custom order

    # For categorical variables
    category_order: Optional[List[Union[str, int, float]]] = None

    def to_dict(self) -> Dict[str, Any]:
        """Convert to dictionary for JSON serialization."""
        return {
            "variable": self.variable,
            "source": self.source.value,
            "label_override": self.label_override,
            "sort_order": self.sort_order,
            "category_order": self.category_order,
        }


@dataclass
class TableMetric:
    """Defines a metric to include in a table."""
    type: MetricType
    label: Optional[str] = None  # Custom label
    decimals: int = 1  # Number of decimal places

    def to_dict(self) -> Dict[str, Any]:
        """Convert to dictionary for JSON serialization."""
        return {
            "type": self.type.value,
            "label": self.label,
            "decimals": self.decimals,
        }


@dataclass
class TableSpecification:
    """
    Defines a single cross-tabulation or summary table.

    Examples:
        - "Satisfaction by Gender" (crosstab)
        - "Age Distribution" (frequency)
        - "Customer Satisfaction Summary" (summary)
    """
    id: str  # Unique identifier (e.g., "tab_001")
    title: str  # Table title
    type: TableType = TableType.CROSSTAB

    # Dimensions
    rows: Optional[TableDimension] = None  # Row variable (for crosstab)
    columns: Optional[TableDimension] = None  # Column variable (for crosstab)
    layers: Optional[List[TableDimension]] = None  # Layer variables (multi-way tables)

    # Metrics to compute
    metrics: List[TableMetric] = field(default_factory=lambda: [
        TableMetric(MetricType.COUNT, "n", 0),
        TableMetric(MetricType.ROW_PERCENT, "Row %", 1),
        TableMetric(MetricType.COLUMN_PERCENT, "Column %", 1),
    ])

    # Weight variable
    weight_variable: Optional[str] = None

    # Statistical tests
    include_chi_square: bool = True
    include_cramers_v: bool = True
    significance_level: float = 0.05

    # Display settings
    show_percent_sign: bool = True
    suppress_small_counts: bool = True
    small_count_threshold: int = 5

    # Indicators referenced (if applicable)
    indicator_ids: List[str] = field(default_factory=list)

    # Recoding to apply before generating table
    recodings: List[RecodingRule] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        """Convert to dictionary for JSON serialization."""
        return {
            "id": self.id,
            "title": self.title,
            "type": self.type.value,
            "rows": self.rows.to_dict() if self.rows else None,
            "columns": self.columns.to_dict() if self.columns else None,
            "layers": [l.to_dict() for l in self.layers] if self.layers else None,
            "metrics": [m.to_dict() for m in self.metrics],
            "weight_variable": self.weight_variable,
            "include_chi_square": self.include_chi_square,
            "include_cramers_v": self.include_cramers_v,
            "significance_level": self.significance_level,
            "show_percent_sign": self.show_percent_sign,
            "suppress_small_counts": self.suppress_small_counts,
            "small_count_threshold": self.small_count_threshold,
            "indicator_ids": self.indicator_ids,
            "recodings": [r.to_dict() for r in self.recodings],
        }



@dataclass
class TableSpecificationDocument:
    """
    Root document for the consolidated table specification.

    This is the primary artifact generated by AI (via skills) and consumed
    by the library modules for computation.

    Structure:
        - metadata: Document metadata
        - global_recodings: Recoding rules applied to all tables
        - indicators: Indicator definitions
        - tables: Table specifications
        - output_settings: Output generation settings
    """
    # Document metadata
    version: str = "1.0"
    generated_at: Optional[str] = None  # ISO 8601 timestamp
    source_file: Optional[str] = None  # Original .sav file name

    # Content
    global_recodings: List[RecodingRule] = field(default_factory=list)
    indicators: List[Indicator] = field(default_factory=list)
    tables: List[TableSpecification] = field(default_factory=list)
    output_settings: OutputSettings = field(default_factory=OutputSettings)

    # Free-form notes (for human review)
    notes: Optional[str] = None

    def __post_init__(self):
        """Set generated_at timestamp if not provided."""
        if self.generated_at is None:
            self.generated_at = datetime.utcnow().isoformat() + "Z"

    def to_dict(self) -> Dict[str, Any]:
        """Convert to dictionary for JSON serialization."""
        return {
            "metadata": {
                "version": self.version,
                "generated_at": self.generated_at,
                "source_file": self.source_file,
            },
            "global_recodings": [r.to_dict() for r in self.global_recodings],
            "indicators": [i.to_dict() for i in self.indicators],
            "tables": [t.to_dict() for t in self.tables],
            "output_settings": self.output_settings.to_dict(),
            "notes": self.notes,
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "TableSpecificationDocument":
        """Create instance from dictionary (for loading from JSON)."""
        metadata = data.get("metadata", {})
        output_settings_data = data.get("output_settings", {})

        # Parse global recodings
        global_recodings = []
        for r_data in data.get("global_recodings", []):
            recoding = RecodingRule(
                variable=r_data["variable"],
                new_variable=r_data.get("new_variable"),
                type=RecodingType(r_data["type"]),
                label=r_data.get("label"),
                value_mappings=r_data.get("value_mappings", {}),
                range_mappings=[
                    RangeMapping(
                        min_value=r.get("min_value"),
                        max_value=r.get("max_value"),
                        recoded_value=r.get("recoded_value", ""),
                        inclusive=r.get("inclusive", True),
                    )
                    for r in r_data.get("range_mappings", [])
                ],
                conditions=r_data.get("conditions", []),
                condition_values=r_data.get("condition_values", []),
                value_labels=r_data.get("value_labels", {}),
                missing_values=r_data.get("missing_values", []),
            )
            global_recodings.append(recoding)

        # Parse indicators
        indicators = []
        for i_data in data.get("indicators", []):
            variables = [
                VariableRef(
                    name=v["name"],
                    source=VariableSource(v.get("source", "raw")),
                    recoded_as=v.get("recoded_as"),
                    weight=v.get("weight", 1.0),
                )
                for v in i_data.get("variables", [])
            ]
            recoding = None
            if i_data.get("recoding"):
                r_data = i_data["recoding"]
                recoding = RecodingRule(
                    variable=r_data["variable"],
                    new_variable=r_data.get("new_variable"),
                    type=RecodingType(r_data["type"]),
                    label=r_data.get("label"),
                    value_mappings=r_data.get("value_mappings", {}),
                    range_mappings=[
                        RangeMapping(
                            min_value=r.get("min_value"),
                            max_value=r.get("max_value"),
                            recoded_value=r.get("recoded_value", ""),
                            inclusive=r.get("inclusive", True),
                        )
                        for r in r_data.get("range_mappings", [])
                    ],
                    conditions=r_data.get("conditions", []),
                    condition_values=r_data.get("condition_values", []),
                    value_labels=r_data.get("value_labels", {}),
                    missing_values=r_data.get("missing_values", []),
                )

            indicator = Indicator(
                id=i_data["id"],
                name=i_data["name"],
                description=i_data.get("description"),
                variables=variables,
                aggregation=AggregationType(i_data.get("aggregation", "mean")),
                recoding=recoding,
                value_labels=i_data.get("value_labels", {}),
                format_string=i_data.get("format_string"),
                reverse_coded=i_data.get("reverse_coded", False),
            )
            indicators.append(indicator)

        # Parse tables
        tables = []
        for t_data in data.get("tables", []):
            rows = None
            if t_data.get("rows"):
                r_data = t_data["rows"]
                rows = TableDimension(
                    variable=r_data["variable"],
                    source=VariableSource(r_data.get("source", "raw")),
                    label_override=r_data.get("label_override"),
                    sort_order=r_data.get("sort_order"),
                    category_order=r_data.get("category_order"),
                )

            columns = None
            if t_data.get("columns"):
                c_data = t_data["columns"]
                columns = TableDimension(
                    variable=c_data["variable"],
                    source=VariableSource(c_data.get("source", "raw")),
                    label_override=c_data.get("label_override"),
                    sort_order=c_data.get("sort_order"),
                    category_order=c_data.get("category_order"),
                )

            layers = None
            if t_data.get("layers"):
                layers = [
                    TableDimension(
                        variable=l_data["variable"],
                        source=VariableSource(l_data.get("source", "raw")),
                        label_override=l_data.get("label_override"),
                        sort_order=l_data.get("sort_order"),
                        category_order=l_data.get("category_order"),
                    )
                    for l_data in t_data["layers"]
                ]

            metrics = [
                TableMetric(
                    type=MetricType(m["type"]),
                    label=m.get("label"),
                    decimals=m.get("decimals", 1),
                )
                for m in t_data.get("metrics", [])
            ]

            recodings = []
            for r_data in t_data.get("recodings", []):
                recoding = RecodingRule(
                    variable=r_data["variable"],
                    new_variable=r_data.get("new_variable"),
                    type=RecodingType(r_data["type"]),
                    label=r_data.get("label"),
                    value_mappings=r_data.get("value_mappings", {}),
                    range_mappings=[
                        RangeMapping(
                            min_value=r.get("min_value"),
                            max_value=r.get("max_value"),
                            recoded_value=r.get("recoded_value", ""),
                            inclusive=r.get("inclusive", True),
                        )
                        for r in r_data.get("range_mappings", [])
                    ],
                    conditions=r_data.get("conditions", []),
                    condition_values=r_data.get("condition_values", []),
                    value_labels=r_data.get("value_labels", {}),
                    missing_values=r_data.get("missing_values", []),
                )
                recodings.append(recoding)

            table = TableSpecification(
                id=t_data["id"],
                title=t_data["title"],
                type=TableType(t_data.get("type", "crosstab")),
                rows=rows,
                columns=columns,
                layers=layers,
                metrics=metrics,
                weight_variable=t_data.get("weight_variable"),
                include_chi_square=t_data.get("include_chi_square", True),
                include_cramers_v=t_data.get("include_cramers_v", True),
                significance_level=t_data.get("significance_level", 0.05),
                show_percent_sign=t_data.get("show_percent_sign", True),
                suppress_small_counts=t_data.get("suppress_small_counts", True),
                small_count_threshold=t_data.get("small_count_threshold", 5),
                indicator_ids=t_data.get("indicator_ids", []),
                recodings=recodings,
            )
            tables.append(table)

        # Parse output settings
        output_settings = OutputSettings(
            significance_threshold=output_settings_data.get("significance_threshold", 0.05),
            min_cramers_v=output_settings_data.get("min_cramers_v", 0.1),
            min_sample_size=output_settings_data.get("min_sample_size", 30),
            include_powerpoint=output_settings_data.get("include_powerpoint", True),
            include_html_dashboard=output_settings_data.get("include_html_dashboard", True),
            include_csv_export=output_settings_data.get("include_csv_export", True),
            ppt_template=output_settings_data.get("ppt_template"),
            max_tables_ppt=output_settings_data.get("max_tables_ppt", 20),
            dashboard_title=output_settings_data.get("dashboard_title", "Survey Analysis Results"),
            include_charts=output_settings_data.get("include_charts", True),
            chart_type=output_settings_data.get("chart_type", "heatmap"),
            output_directory=output_settings_data.get("output_directory", "output"),
        )

        return cls(
            version=metadata.get("version", "1.0"),
            generated_at=metadata.get("generated_at"),
            source_file=metadata.get("source_file"),
            global_recodings=global_recodings,
            indicators=indicators,
            tables=tables,
            output_settings=output_settings,
            notes=data.get("notes"),
        )



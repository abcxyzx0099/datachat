def create_empty_spec(source_file: Optional[str] = None) -> TableSpecificationDocument:
    """Create an empty table specification document."""
    return TableSpecificationDocument(
        version="1.0",
        source_file=source_file,
    )


def validate_spec_structure(spec: Dict[str, Any]) -> List[str]:
    """
    Perform basic structural validation of a table specification.

    Returns a list of error messages (empty if valid).
    """
    errors = []

    # Check metadata
    if "metadata" not in spec:
        errors.append("Missing 'metadata' section")

    # Check required sections exist
    required_sections = ["tables", "output_settings"]
    for section in required_sections:
        if section not in spec:
            errors.append(f"Missing required section: '{section}'")

    # Validate tables
    tables = spec.get("tables", [])
    if not tables:
        errors.append("No tables defined in specification")

    for i, table in enumerate(tables):
        if "id" not in table:
            errors.append(f"Table {i}: missing 'id'")
        if "title" not in table:
            errors.append(f"Table {i}: missing 'title'")
        if "type" not in table:
            errors.append(f"Table {i}: missing 'type'")

        # For crosstabs, need rows and columns
        if table.get("type") == "crosstab":
            if not table.get("rows") and not table.get("columns"):
                errors.append(f"Table {i} ({table.get('id', 'unknown')}): crosstab requires rows or columns")

    # Validate output settings
    output_settings = spec.get("output_settings", {})
    if "significance_threshold" in output_settings:
        threshold = output_settings["significance_threshold"]
        if not 0 < threshold <= 1:
            errors.append(f"significance_threshold must be between 0 and 1, got {threshold}")

    return errors

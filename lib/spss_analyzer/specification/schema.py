@dataclass
class OutputSettings:
    """Settings for report generation."""
    # Significance filtering
    significance_threshold: float = 0.05
    min_cramers_v: float = 0.1
    min_sample_size: int = 30

    # Output formats
    include_powerpoint: bool = True
    include_html_dashboard: bool = True
    include_csv_export: bool = True

    # PowerPoint settings
    ppt_template: Optional[str] = None
    max_tables_ppt: int = 20  # Only significant tables in PPT

    # HTML dashboard settings
    dashboard_title: str = "Survey Analysis Results"
    include_charts: bool = True
    chart_type: Literal["bar", "column", "heatmap", "mosaic"] = "heatmap"

    # File paths
    output_directory: str = "output"

    def to_dict(self) -> Dict[str, Any]:
        """Convert to dictionary for JSON serialization."""
        return {
            "significance_threshold": self.significance_threshold,
            "min_cramers_v": self.min_cramers_v,
            "min_sample_size": self.min_sample_size,
            "include_powerpoint": self.include_powerpoint,
            "include_html_dashboard": self.include_html_dashboard,
            "include_csv_export": self.include_csv_export,
            "ppt_template": self.ppt_template,
            "max_tables_ppt": self.max_tables_ppt,
            "dashboard_title": self.dashboard_title,
            "include_charts": self.include_charts,
            "chart_type": self.chart_type,
            "output_directory": self.output_directory,
        }


